#upper case
name = "taqi tahmid"
print(name.upper())

#lower case
name = "TAqi TahMID"
print(name.lower())

#strip() removes all the whitespace from the beginning or the ending..not from the middle
country = "                      Bangladesh is my favourite country              "
print(country.strip())

#we can replce string
fruit = "Banana"
print(fruit.replace('an', 'em'))

#we can split string with a specific seperator
a = "Taqi Tahmid Dhrubo"
print(a.split(' '))
b = "Chips,Juice,Biscuit"
print(b.split(','))